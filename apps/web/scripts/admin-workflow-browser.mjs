// Run with admin-workflow-fixture-api.py and an isolated local Next server.
import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const base = process.env.FRONTEND_FIXTURE_WEB_URL || 'http://localhost:3011';
assert(['localhost', '127.0.0.1'].includes(new URL(base).hostname));
const fixture = process.env.FRONTEND_FIXTURE_DIR;
assert(fixture);
const shots = path.join(fixture, 'screenshots');
await fs.mkdir(shots, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH || undefined, args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const checked = name => console.log(`PASS ${name}`);
async function noOverflow() { assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Horizontal overflow'); }
try {
  const catalog = 'artist-library';
  await page.goto(`${base}/artist`);
  await page.getByRole('tab', { name: 'Register artwork', exact: true }).click();
  await page.getByLabel('Title', { exact: true }).fill('Blue study · Admin workflow');
  await page.getByLabel('Artist / claimant name', { exact: true }).fill('Workflow artist');
  await page.locator('input[type="file"]').setInputFiles(path.join(fixture, 'artwork.png'));
  await page.getByText('Advanced registration settings', { exact: true }).click();
  await page.getByLabel('Catalog', { exact: true }).fill(catalog);
  await page.getByRole('button', { name: 'Register reference', exact: true }).click();
  await page.getByRole('heading', { name: 'Artwork permissions', exact: true }).waitFor();
  assert(await page.getByRole('tab', { name: /^Artwork library/ }).getAttribute('aria-selected') === 'true');
  checked('Simplified Artist registration opens the library and permissions workspace');
  await page.goto(`${base}/user`);
  const form = page.locator('form.scanCard');
  await form.locator('input[name="catalog_id"]').fill(catalog);
  await form.locator('input[type="file"]').setInputFiles(path.join(fixture, 'artwork.png'));
  await form.getByLabel('Your country', { exact: true }).selectOption('US');
  await form.getByLabel('Public image or page URL', { exact: true }).fill('https://example.com/posts/reused-study');
  await form.locator('summary').filter({ hasText: 'More details about your intended use' }).click();
  await form.getByLabel('Publication country', { exact: true }).fill('DE');
  await form.getByLabel('Publication channel', { exact: true }).fill('web');
  await form.getByLabel('Audience', { exact: true }).fill('public');
  const submitted = page.waitForResponse(r => r.url() === `${base}/api/scans` && r.request().method() === 'POST');
  await form.getByRole('button', { name: 'Run CreatorProof analysis', exact: true }).click();
  const response = await submitted;
  assert(response.ok(), await response.text());
  const scan = await response.json();
  await page.getByRole('heading', { name: 'Saved for Admin review', exact: true }).waitFor({ timeout: 60000 });
  checked('User match shows a server-confirmed saved Admin receipt');
  await page.getByRole('link', { name: 'Open review', exact: false }).click();
  await page.getByRole('heading', { name: 'Why this needs review', exact: true }).waitFor({ timeout: 30000 });
  const comparison = page.locator('.adminComparison');
  await comparison.locator('img').last().waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll('.adminComparison img')].length === 2 && [...document.querySelectorAll('.adminComparison img')].every(img => img.complete && img.naturalWidth > 0));
  assert((await page.locator('.adminFacts').allTextContents()).join(' ').includes('US · supplied by the submitting user'));
  assert((await page.locator('.adminFacts').allTextContents()).join(' ').includes('Intended publication countryDE'));
  await page.getByRole('link', { name: 'https://example.com/posts/reused-study', exact: false }).waitFor();
  await page.getByRole('button', { name: 'Record action', exact: true }).waitFor();
  await noOverflow();
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: path.join(shots, 'admin-comparison-desktop.png'), fullPage: true });
  checked('Admin receives the retained comparison, artist, declared country, publication context and public source');
  await page.getByRole('tab', { name: 'Detailed evidence', exact: true }).click();
  await page.getByRole('heading', { name: 'Evidence Matrix', exact: true }).waitFor();
  checked('Detailed evidence stays in a separate case tab');
  await page.getByRole('tab', { name: 'Prepare notice', exact: true }).click();
  await page.getByLabel('Claimant name', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Claimant name', { exact: true }).inputValue(), 'Workflow artist');
  assert.equal(await page.getByLabel('Jurisdiction', { exact: true }).inputValue(), 'US');
  await page.getByLabel('Claimant email', { exact: true }).fill('artist@example.com');
  await page.getByLabel('Protected work URL', { exact: true }).fill('https://example.com/artwork/blue-study');
  await page.getByRole('button', { name: 'Generate notice', exact: true }).click();
  await page.getByLabel('Generated takedown notice', { exact: true }).waitFor({ timeout: 30000 });
  assert((await page.getByLabel('Generated takedown notice', { exact: true }).inputValue()).includes('https://example.com/posts/reused-study'));
  assert(await page.getByRole('button', { name: 'Open notice in email', exact: false }).isDisabled());
  await page.getByLabel('I have reviewed the claimant authority, evidence, URLs and notice wording.', { exact: true }).check();
  assert(await page.getByRole('button', { name: 'Open notice in email', exact: false }).isDisabled(), 'Recipient required');
  checked('A supported match generates a saved notice; email requires human review and a recipient');
  await page.reload();
  await page.getByRole('heading', { name: 'Why this needs review', exact: true }).waitFor({ timeout: 30000 });
  await page.getByRole('tab', { name: 'Prepare notice', exact: true }).click();
  await page.locator('summary').filter({ hasText: 'Saved notice drafts' }).click();
  await page.getByRole('button', { name: 'View saved draft', exact: true }).first().click();
  await page.getByLabel('Generated takedown notice', { exact: true }).waitFor();
  assert(await page.getByRole('button', { name: 'Open notice in email', exact: false }).isDisabled());
  checked('Saved notice survives reload and cannot be handed off with unrelated form context');
  await page.getByRole('tab', { name: 'Review & decide', exact: true }).click();
  await page.getByRole('button', { name: 'Reject before publishing', exact: false }).click();
  await page.getByRole('button', { name: 'Record action', exact: true }).click();
  await page.getByText('rejected for publication', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Back to inbox', exact: false }).click();
  await page.getByLabel('Show', { exact: true }).selectOption('all');
  assert(await page.locator('.adminInboxRow').count() >= 1);
  checked('Admin decision is recorded and its resolved flag remains in history');
  for (const width of [390, 640, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    for (const name of ['Monitoring', 'History', 'Review inbox']) {
      await page.getByRole('tab', { name: name === 'Review inbox' ? /^Review inbox/ : name, exact: name !== 'Review inbox' }).click();
      await noOverflow();
    }
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.adminInboxRow').first().click();
  await page.getByRole('heading', { name: 'Why this needs review', exact: true }).waitFor();
  await noOverflow();
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: path.join(shots, 'admin-comparison-mobile.png'), fullPage: true });
  checked('Admin sections and selected review fit mobile, tablet and desktop widths');
  assert.deepEqual(errors, []);
  await fs.writeFile(path.join(fixture, 'admin-workflow-browser-result.json'), JSON.stringify({ scan_id: scan.id, browser_errors: errors, checks_passed: 8 }, null, 2));
} finally { await browser.close(); }
