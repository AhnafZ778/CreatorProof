// Read-only verification of an already preloaded, local Admin collection.
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || "playwright");
const base = process.env.STORED_CASES_WEB_URL || "http://localhost:3000";
assert(["localhost", "127.0.0.1"].includes(new URL(base).hostname));
const output = process.env.STORED_CASES_OUTPUT_DIR || "/tmp/creatorproof-stored-cases-browser";
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH || undefined, args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
const mutations = [];
page.on("pageerror", error => errors.push(error.message));
page.on("request", request => { if (!["GET", "HEAD"].includes(request.method()) && request.url().includes("/api/")) mutations.push(request.url()); });
const checks = [];
const checked = text => { checks.push(text); console.log(`PASS ${text}`); };
try {
  await page.goto(`${base}/admin`);
  await page.getByRole("heading", { name: "Every image. The full story.", exact: true }).waitFor();
  await page.locator(".storedCaseCard").first().waitFor({ timeout: 30000 });
  const count = await page.locator(".storedCaseCard").count();
  assert(count >= 3);
  assert.equal(await page.getByRole("tab", { name: "Stored cases", exact: true }).getAttribute("aria-selected"), "true");
  await page.waitForFunction(() => [...document.querySelectorAll(".storedCardImages img")].every(image => image.complete && image.naturalWidth > 0));
  assert(!(await page.locator("main").innerText()).toLowerCase().includes("demo"));
  await page.screenshot({ path: path.join(output, "stored-cases-desktop.png"), fullPage: true });
  checked("Admin opens with saved paired images and selectable case cards");
  await page.getByRole("button", { name: "AI edits", exact: true }).click();
  assert.equal(await page.locator(".storedCaseCard").count(), 1);
  await page.locator(".storedCaseCard").click();
  await page.getByRole("heading", { name: "Why this needs review", exact: true }).waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll(".adminComparison img")].every(image => image.complete && image.naturalWidth > 0));
  await page.getByText("AI edit record:", { exact: true }).waitFor();
  await page.getByRole("tab", { name: "Detailed evidence", exact: true }).click();
  await page.getByRole("heading", { name: "Evidence Matrix", exact: true }).waitFor();
  checked("Documented AI edit opens its saved images and real evidence matrix");
  await page.getByRole("tab", { name: "Prepare notice", exact: true }).click();
  assert(await page.getByLabel("Claimant name", { exact: true }).inputValue());
  assert(await page.getByLabel("Claimant email", { exact: true }).inputValue());
  assert((await page.getByLabel("Protected work URL", { exact: true }).inputValue()).includes("/collection/nocturne"));
  assert((await page.getByLabel("Public URL of the flagged image", { exact: true }).inputValue()).includes("/collection/nocturne-sky-edit"));
  const notice = await page.getByLabel("Generated takedown notice", { exact: true }).inputValue();
  assert(notice.includes("PREPARED FOR OPERATOR REVIEW"));
  assert(notice.includes("SHA-256"));
  assert(await page.getByRole("button", { name: "Open notice in email", exact: false }).isDisabled());
  await page.screenshot({ path: path.join(output, "stored-notice-desktop.png"), fullPage: true });
  checked("Notice and complete case context open immediately without generation or handoff");
  const response = await context.request.get(`${base}/api/admin/stored-cases?limit=200`);
  assert(response.ok());
  const cases = await response.json();
  const source = cases.find(row => row.stored_case?.comparison_kind === "AI_EDIT");
  const view = await context.request.get(source.source_url);
  assert(view.ok());
  assert((await view.text()).includes("AI-assisted sky edit"));
  await page.getByRole("button", { name: "Back to stored cases", exact: true }).click();
  await page.getByRole("button", { name: "All comparisons", exact: true }).click();
  await page.reload();
  await page.locator(".storedCaseCard").first().waitFor();
  assert.equal(await page.locator(".storedCaseCard").count(), count);
  checked("Collection pages exist and stored cases survive reload");
  for (const width of [390, 640, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Overflow at ${width}`);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, "stored-cases-mobile.png"), fullPage: true });
  await page.locator(".storedCaseCard").first().click();
  await page.getByRole("heading", { name: "Why this needs review", exact: true }).waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: path.join(output, "stored-comparison-mobile.png"), fullPage: true });
  checked("Gallery and selected cases fit mobile, tablet and desktop widths");
  assert.deepEqual(errors, []);
  assert.deepEqual(mutations, []);
  checked("Presenting stored cases performs no scan, inference, decision or notice mutation");
  await fs.writeFile(path.join(output, "verification.json"), JSON.stringify({ cases: count, checks, browser_errors: errors, mutations }, null, 2));
} finally { await browser.close(); }
